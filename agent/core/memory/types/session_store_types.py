"""Explicit three-state persistence interfaces; entities remain independent."""
from typing import Protocol
from ..session_workspace import SessionWorkspace, WorkspaceItem, WorkspaceItemStatus
from ..session_narrative import GoalContract, NarrativeItem, WorkingSet
from ..session_state import SessionState, SessionStateItem, StateRef

class WorkspaceStore(Protocol):
    def create(self, workspace: SessionWorkspace, *, contract: GoalContract | None = None) -> SessionWorkspace: ...
    def get(self, session_id: str) -> SessionWorkspace | None: ...
    def get_item(self, session_id: str, item_id: str) -> WorkspaceItem | None: ...
    def replace_plan(self, session_id: str, items: tuple[WorkspaceItem, ...], *,
                     expected_revision: int, actor: str, reason: str) -> SessionWorkspace: ...
    def set_item_status(self, session_id: str, item_id: str, status: WorkspaceItemStatus, *,
                        expected_revision: int, actor: str, reason: str,
                        turn_id: str | None = None, tool_call_ids: tuple[str, ...] | None = None) -> WorkspaceItem: ...

class NarrativeStore(Protocol):
    def append_contract(self, contract: GoalContract, *, expected_revision: int) -> GoalContract: ...
    def append(self, item: NarrativeItem) -> NarrativeItem: ...
    def get_contract(self, session_id: str, revision: int | None = None) -> GoalContract | None: ...
    def list_events(self, session_id: str, *, limit: int = 100, offset: int = 0) -> tuple[NarrativeItem, ...]: ...
    def build_working_set(self, session_id: str, *, contract_revision: int | None = None,
                          item_id: str | None = None, event_ids: tuple[str, ...] = (),
                          state_refs: tuple[StateRef, ...] = ()) -> WorkingSet: ...

class StateStore(Protocol):
    def put(self, item: SessionStateItem, *, expected_revision: int) -> SessionStateItem: ...
    def get(self, ref: StateRef) -> SessionStateItem | None: ...
    def get_current(self, session_id: str, scope_key: str, key: str) -> SessionStateItem | None: ...
    def list_current(self, session_id: str) -> SessionState: ...
    def list_history(self, session_id: str, scope_key: str, key: str, *,
                      limit: int = 100, offset: int = 0) -> tuple[SessionStateItem, ...]: ...
    def invalidate(self, ref: StateRef, *, reason: str, actor: str) -> SessionStateItem: ...
